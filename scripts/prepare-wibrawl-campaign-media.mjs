import sharp from 'sharp';
import { readFileSync, writeFileSync } from 'node:fs';

// Compress existing artwork; never generate or replace a product design here.
for (const width of [480, 720, 960, 1440]) {
  await sharp('public/wibrawl/streetwear-campaign-1440.webp')
    .resize({ width, withoutEnlargement: true })
    .avif({ quality: 45, effort: 6 })
    .toFile(`public/wibrawl/streetwear-campaign-${width}.avif`);
}
for (const theme of ['gaming', 'sports']) {
  await sharp(`public/wibrawl/${theme}-campaign-640.webp`)
    .resize({ width: 96, withoutEnlargement: true })
    .webp({ quality: 76, effort: 6 })
    .toFile(`public/wibrawl/${theme}-campaign-96.webp`);
}
const firstImage = readFileSync('public/wibrawl/streetwear-campaign-960.avif');
if (firstImage.length > 36000) throw Error('Campaign exceeds first-screen image budget');
writeFileSync('src/wibrawl-first-screen-image.js', `// Generated by scripts/prepare-wibrawl-campaign-media.mjs. Server-only; never imported by the browser bundle.\nexport const wibrawlFirstScreenImage = ${JSON.stringify('data:image/avif;base64,' + firstImage.toString('base64'))};\n`);
