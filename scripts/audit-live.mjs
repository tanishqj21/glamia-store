const checks = {};
const home = await (await fetch("https://glamiastore.com/", { headers: { "Cache-Control": "no-cache" } })).text();
const prod = await (await fetch("https://glamiastore.com/product/night-suit-sage-green", { headers: { "Cache-Control": "no-cache" } })).text();
checks.fontsPreconnect = home.includes("fonts.googleapis.com");
checks.favicon = home.includes("favicon.svg");
checks.splashSkipScript = home.includes("glamia-splash");
checks.cspHeader = (await (await fetch("https://glamiastore.com/", { headers: { "Cache-Control": "no-cache" } })).headers.get("content-security-policy") || "").includes("sha256");
checks.slugUrls = prod.includes("/product/night-suit-sage-green");
checks.jsonLd = prod.includes("application/ld+json") && prod.includes("schema.org");
checks.metaDescription = (prod.match(/name="description" content="([^"]{10,60})/) || [])[1] || "(missing)";
checks.title = (prod.match(/<title>([^<]+)/) || [])[1];
const sm = await (await fetch("https://glamiastore.com/sitemap.xml")).text();
checks.sitemapUrls = (sm.match(/<loc>/g) || []).length;
checks.sitemapImages = (sm.match(/<image:loc>/g) || []).length;
const robots = await (await fetch("https://glamiastore.com/robots.txt")).text();
checks.robotsAllowsImages = robots.includes("Allow: /api/assets/");
const tracking = await fetch("https://glamiastore.com/api/analytics/track", { method: "POST", headers: { "Content-Type": "application/json", "Origin": "https://glamiastore.com" }, body: JSON.stringify({ path: "/", referrer: "" }) });
checks.analyticsLive = tracking.status;
checks.ogTags = (home.match(/property="og:/g) || []).length;
console.log(JSON.stringify(checks, null, 2));
