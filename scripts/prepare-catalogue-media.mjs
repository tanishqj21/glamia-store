// Copy public thumbnails byte-for-byte to Worker Assets. R2 originals and
// product records are never modified. New thumbnails retain their normal URL.
import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const origin = 'https://glamiastore.com';
const manifest = {};
await mkdir('public/catalogue-media', { recursive: true });
for (let page = 1; page <= 100; page++) {
  const response = await fetch(`${origin}/api/products?view=cards&limit=100&page=${page}`);
  if (!response.ok) throw Error('Public catalogue unavailable');
  const data = await response.json();
  for (const product of data.products || []) {
    const source = product.thumbnail_url;
    if (!/^\/api\/assets\/products\/thumbs\/[\w-]+\/[a-f\d-]{36}\.webp$/i.test(source || '') || manifest[source]) continue;
    const image = await fetch(origin + source, { signal: AbortSignal.timeout(15000) });
    if (!image.ok || !/^image\/webp(?:;|$)/i.test(image.headers.get('content-type') || '')) throw Error('Unexpected public thumbnail response');
    if (Number(image.headers.get('content-length')) > 65536) throw Error('Thumbnail exceeds budget');
    const bytes = Buffer.from(await image.arrayBuffer());
    if (!bytes.length || bytes.length > 65536) throw Error('Thumbnail exceeds budget');
    const hash = createHash('sha256').update(bytes).digest('hex');
    const file = `catalogue-media/${hash.slice(0, 24)}.webp`;
    await writeFile('public/' + file, bytes);
    manifest[source] = { url: '/' + file, sha256: hash, bytes: bytes.length };
  }
  if (!data.pagination?.has_more) break;
  if (page === 100) throw Error('Public catalogue exceeds explicit bound');
}
await writeFile('react-app/src/lib/catalogueMediaManifest.js', `// Generated byte-identical public thumbnails; original URLs remain fallbacks.\nexport const catalogueMediaManifest = ${JSON.stringify(manifest, null, 2)};\n`);
console.log(`Prepared ${Object.keys(manifest).length} byte-identical public thumbnails.`);
